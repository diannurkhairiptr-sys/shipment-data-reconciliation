-- 03_reconciliation_query.sql
-- Compare source shipment totals with records in the shipment database.

WITH C AS (
    SELECT
        DELIVERY_NUMBER,
        SUBSTR(DELIVERY_NUMBER, 1, 1)
            || SUBSTR(DELIVERY_NUMBER, -8) AS SHIPMENT_ID,
        SUM(COLLI_COUNT) AS SOURCE_COLLI,
        SUM(SOURCE_QTY) AS SOURCE_QTY
    FROM SHIPMENT_SOURCE
    GROUP BY DELIVERY_NUMBER
),
M AS (
    SELECT
        I.SHIPMENT_ID,
        COUNT(DISTINCT I.CARTON_ID) AS DATABASE_COLLI,
        SUM(I.DATABASE_QTY) AS DATABASE_QTY
    FROM SHIPMENT_DATABASE I
    JOIN C
        ON C.SHIPMENT_ID = I.SHIPMENT_ID
    GROUP BY I.SHIPMENT_ID
)
SELECT
    C.DELIVERY_NUMBER,
    C.SHIPMENT_ID,
    C.SOURCE_COLLI,
    C.SOURCE_QTY,
    NVL(M.DATABASE_COLLI, 0) AS DATABASE_COLLI,
    NVL(M.DATABASE_QTY, 0) AS DATABASE_QTY,
    C.SOURCE_COLLI - NVL(M.DATABASE_COLLI, 0) AS DIFFERENCE_COLLI,
    C.SOURCE_QTY - NVL(M.DATABASE_QTY, 0) AS DIFFERENCE_QTY,
    CASE
        WHEN M.SHIPMENT_ID IS NULL THEN 'NOT FOUND'
        WHEN C.SOURCE_COLLI = M.DATABASE_COLLI
         AND C.SOURCE_QTY = M.DATABASE_QTY THEN 'MATCH'
        ELSE 'MISMATCH'
    END AS STATUS
FROM C
LEFT JOIN M
    ON M.SHIPMENT_ID = C.SHIPMENT_ID
ORDER BY C.DELIVERY_NUMBER;
